export class BusinessPlannerAgent extends AssistantAgent {
  constructor(options: { modelClient?: any; tools?: string[] } = {}) {
    super(
      'BusinessPlanner',
      `You are an expert business planner specializing in strategic planning, market analysis, and business model development. 
      
      Your expertise includes:
      - Strategic planning and goal setting
      - Market research and competitive analysis
      - Business model canvas development
      - Financial planning and projections
      - Risk assessment and mitigation strategies
      
      You work collaboratively with other agents to create comprehensive business plans and strategies.`,
      {
        tools: [
          'dbUpsertPlan',
          'storageSaveDoc',
          'notionCreatePage',
          ...(options.tools || [])
        ],
        ...options
      }
    )
  }

  async createStrategicPlan(businessGoal: string, constraints: string[] = []): Promise<any> {
    try {
      // Create project structure
      const projectId = `project_${Date.now()}`
      
      // Generate strategic plan using tools
      const planResult = await this.executeTool({
        toolName: 'storageSaveDoc',
        arguments: {
          project_id: projectId,
          filename: 'strategic-plan.md',
          content_md: `# Strategic Plan\n\n## Business Goal\n${businessGoal}\n\n## Constraints\n${constraints.join('\n')}\n\n## Plan Overview\n[To be developed by team collaboration]`
        }
      })

      // Create project milestones and tasks
      const projectResult = await this.executeTool({
        toolName: 'dbUpsertPlan',
        arguments: {
          project_id: projectId,
          milestones: [
            { title: 'Foundation', due_date: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000).toISOString().split('T')[0], order_index: 1 },
            { title: 'Market Analysis', due_date: new Date(Date.now() + 60 * 24 * 60 * 60 * 1000).toISOString().split('T')[0], order_index: 2 },
            { title: 'Strategy Development', due_date: new Date(Date.now() + 90 * 24 * 60 * 60 * 1000).toISOString().split('T')[0], order_index: 3 }
          ],
          tasks: [
            { title: 'Business Model Canvas', priority: 1, due_in_days: 7, owner_agent_key: 'business-planner' },
            { title: 'Market Research', priority: 1, due_in_days: 14, owner_agent_key: 'market-analyst' },
            { title: 'Financial Projections', priority: 2, due_in_days: 21, owner_agent_key: 'finance-expert' }
          ]
        }
      })

      return {
        project_id: projectId,
        plan_document: planResult,
        project_structure: projectResult
      }
    } catch (error: any) {
      throw new Error(`Failed to create strategic plan: ${error.message}`)
    }
  }

  async analyzeBusinessModel(businessIdea: string): Promise<any> {
    // Analyze business model and provide insights
    const analysis = await this.executeTool({
      toolName: 'storageSaveDoc',
      arguments: {
        project_id: `analysis_${Date.now()}`,
        filename: 'business-model-analysis.md',
        content_md: `# Business Model Analysis\n\n## Business Idea\n${businessIdea}\n\n## Analysis\n[Generated by BusinessPlanner agent]\n\n## Recommendations\n[To be developed]`
      }
    })

    return analysis
  }
}

